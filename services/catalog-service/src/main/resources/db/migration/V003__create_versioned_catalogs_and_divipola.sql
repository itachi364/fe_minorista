CREATE TABLE IF NOT EXISTS catalog.catalog_item (
    catalog_code VARCHAR(80) NOT NULL,
    item_code VARCHAR(80) NOT NULL,
    label VARCHAR(180) NOT NULL,
    description VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT true,
    regulatory BOOLEAN NOT NULL DEFAULT false,
    source VARCHAR(80) NOT NULL,
    source_version VARCHAR(40) NOT NULL,
    valid_from DATE,
    valid_to DATE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (catalog_code, item_code)
);

CREATE TABLE IF NOT EXISTS catalog.company_catalog_item_setting (
    company_id UUID NOT NULL,
    catalog_code VARCHAR(80) NOT NULL,
    item_code VARCHAR(80) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT true,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (company_id, catalog_code, item_code),
    CONSTRAINT fk_company_catalog_item FOREIGN KEY (catalog_code, item_code) REFERENCES catalog.catalog_item (catalog_code, item_code)
);

CREATE TABLE IF NOT EXISTS catalog.department (
    department_code VARCHAR(2) PRIMARY KEY,
    department_name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    source VARCHAR(80) NOT NULL,
    source_version VARCHAR(40) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS catalog.municipality (
    municipality_code VARCHAR(5) PRIMARY KEY,
    department_code VARCHAR(2) NOT NULL,
    municipality_name VARCHAR(160) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    source VARCHAR(80) NOT NULL,
    source_version VARCHAR(40) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_municipality_department FOREIGN KEY (department_code) REFERENCES catalog.department (department_code)
);

CREATE INDEX IF NOT EXISTS idx_catalog_item_catalog_active ON catalog.catalog_item (catalog_code, active, sort_order);
CREATE INDEX IF NOT EXISTS idx_company_catalog_setting_company ON catalog.company_catalog_item_setting (company_id, catalog_code);
CREATE INDEX IF NOT EXISTS idx_municipality_department_active ON catalog.municipality (department_code, active, municipality_name);

